import { route } from '../../http'
import type { NulvlessResult, RequestOptions } from '../../types'
import type {
  AuthMethod,
  EnableFactorParams,
  EnrollFactorParams,
  FactorEnrollment,
  Nonce,
  UnenrollFactorParams,
} from '../types'
import { AuthSubClient } from '../base'

/**
 * MFA factor management.
 *
 * Available on both `createClient` (browser) and `createServerClient` (server).
 *
 * All methods require authentication. Pass `options.headers.Authorization` on
 * the server, or rely on the configured storage for automatic token injection.
 */
export class FactorsClient extends AuthSubClient {

  /**
   * Lists all configured MFA factors for the authenticated user.
   */
  async list(options?: RequestOptions): Promise<NulvlessResult<AuthMethod[]>> {
    const auth = await this.bearer(options)
    if (!auth.ok) return { data: null, error: auth.error }
    return this.http.get<AuthMethod[]>('/factors', {
      ...options,
      headers: { ...options?.headers, ...auth.headers },
    })
  }

  /**
   * Returns the user's recovery codes.
   *
   * Requires sudo: `MANAGE_MFA`.
   */
  async getRecoveryCodes(
    params?: Nonce,
    options?: RequestOptions,
  ): Promise<NulvlessResult<{ codes: string[] }>> {
    const auth = await this.bearer(options)
    if (!auth.ok) return { data: null, error: auth.error }
    return this.http.get<{ codes: string[] }>('/factors/codes', {
      ...options,
      nonce: params?.nonce,
      headers: { ...options?.headers, ...auth.headers },
    })
  }

  /**
   * Deletes (invalidates) the user's recovery codes.
   *
   * Requires sudo: `MANAGE_MFA`.
   */
  async deleteRecoveryCodes(params?: Nonce, options?: RequestOptions): Promise<NulvlessResult<null>> {
    const auth = await this.bearer(options)
    if (!auth.ok) return { data: null, error: auth.error }
    return this.http.delete<null>('/factors/codes', {
      ...options,
      nonce: params?.nonce,
      headers: { ...options?.headers, ...auth.headers },
    })
  }

  /**
   * Begins enrolling a new MFA factor. Returns credentials needed to configure
   * the factor on the user's device.
   *
   * For TOTP: use `secret` for manual entry or `url` to generate a QR code.
   * For SMS: pass `phone` to send the codes to a number other than the user's.
   *
   * A user holds up to 10 authenticator apps and SMS factors combined, and one
   * email factor and one set of recovery codes.
   *
   * After the user configures their device, call `enable` with the `token` and
   * the first OTP code to activate the factor.
   *
   * Requires sudo: `MANAGE_MFA`.
   *
   * @example
   * const { data } = await nulvless.auth.factors.enroll({ type: 'totp', name: 'My Authenticator' })
   * // data.url → QR code provisioning URL
   * // data.secret → manual entry secret
   * // data.token → pass to factors.enable
   */
  async enroll(params: EnrollFactorParams, options?: RequestOptions): Promise<NulvlessResult<FactorEnrollment>> {
    const auth = await this.bearer(options)
    if (!auth.ok) return { data: null, error: auth.error }
    const { nonce, type, name, phone } = params
    const body = { ...(name ? { name } : {}), ...(phone ? { phone } : {}) }
    return this.http.post<FactorEnrollment>(route`/factors/${type}`, body, {
      ...options,
      nonce,
      headers: { ...options?.headers, ...auth.headers },
    })
  }

  /**
   * Activates a pending factor enrollment by confirming the first OTP code.
   *
   * Pass the `token` from `enroll` and the code generated by the user's device.
   */
  async enable(params: EnableFactorParams, options?: RequestOptions): Promise<NulvlessResult<null>> {
    const auth = await this.bearer(options)
    if (!auth.ok) return { data: null, error: auth.error }
    return this.http.post<null>('/factors', params, {
      ...options,
      headers: { ...options?.headers, ...auth.headers },
    })
  }

  /**
   * Unenrolls (removes) an MFA factor by its ID.
   *
   * Use `factors.list()` to retrieve the factor `id` before calling this.
   * Returns the removed factor.
   *
   * Requires sudo: `MANAGE_MFA`.
   *
   * @example
   * const { data: factors } = await nulvless.auth.factors.list()
   * const totp = factors?.find(f => f.type === 'totp')
   * if (totp?.id) await nulvless.auth.factors.unenroll({ id: totp.id })
   */
  async unenroll(params: UnenrollFactorParams, options?: RequestOptions): Promise<NulvlessResult<AuthMethod>> {
    const auth = await this.bearer(options)
    if (!auth.ok) return { data: null, error: auth.error }
    const { nonce, id } = params
    return this.http.delete<AuthMethod>(route`/factors/${id}`, {
      ...options,
      nonce,
      headers: { ...options?.headers, ...auth.headers },
    })
  }

}
